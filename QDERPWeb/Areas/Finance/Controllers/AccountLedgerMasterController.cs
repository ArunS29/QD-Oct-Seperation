        [HttpGet("GetMaxLedgerAccountID")]
        public async Task<ActionResult> GetMaxLedgerAccountID()
        {
            var nextAccountId = (from account in _context.Tbl201ChartOfAccounts
                                 where account.AccountId.StartsWith("L0")
                                 orderby account.AccountId descending
                                 select account.AccountId)
                    .Take(1)
                    .Select(accountId => "L" + (int.Parse(accountId.Substring(1)) + 1).ToString().PadLeft(accountId.Substring(1).Length, '0')).FirstOrDefault();

            return Json(new { nextAccountId });
        }

        [HttpGet("FindDuplicatesOnAccountHead")]
        public async Task<ActionResult> FindDuplicatesOnAccountHead(string stAccountHeadValue)
        {
            var result = (from c in _context.Tbl201ChartOfAccounts
                          where c.AccountHead.ToUpper() == stAccountHeadValue.ToUpper()  // Case-insensitive comparison
                          group c by c.AccountHead into g
                          select new
                          {
                              MaxAccountId = g.Max(x => x.AccountId),  // Get the max AccountId for each AccountHead
                              IsValid = g.Count() > 0 ? true : false,
                              AccountHead = g.Key  // Grouped AccountHead
                          }).ToList();

            return Json(result);
        }

        [HttpGet("GetAttachments")]
        public async Task<ActionResult> GetAttachments()
        {
            string LedgerNo = "L00506";
            var query = from a in _context.Tbl20116LedgerDocuments
                        join b in _context.Tbl101DocumentTypes on a.DocumentType equals b.DocumentTypeId
                        join c in _context.Tbl201ChartOfAccounts on a.LedgerNo equals c.AccountId
                        where c.AccountId == LedgerNo
                        select new
                        {
                            DocumentType = b.DocumentType,
                            DocumentRefNo = a.DocumentRefNo,
                            DocumentExpDate = a.DocumentExpDate,
                            DocumentNotificationDate = a.DocumentNotificationDate
                        };

            return Json(query);
        }

