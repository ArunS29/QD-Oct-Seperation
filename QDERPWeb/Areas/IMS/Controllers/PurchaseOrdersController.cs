      [HttpPost]
public async Task<IActionResult> SavePurchaseOrder([FromBody] PurchaseOrderViewModel model)
{
    if (model == null || model.Master == null)
        return BadRequest(new { success = false, message = "Invalid data." });

    if (!_tenantDbContextHelper.TryGetTenantAndDbContext(out var tenant, out var dbContext))
        return Unauthorized(new { success = false, message = "Invalid tenant." });

    var strategy = dbContext.Database.CreateExecutionStrategy();
    try
    {
        await strategy.ExecuteAsync(async () =>
        {
            using var transaction = await dbContext.Database.BeginTransactionAsync();

            var master = model.Master;
            var children = model.Children ?? new List<Tbl60402purchaseOrderChild>();
            var pono = master.Pono?.Trim();
            string userName = HttpContext.Session.GetString("UserName") ?? "System";

            // --- MASTER UPSERT ---
            var existingPo = await dbContext.Tbl60401purchaseOrderMasters
                     .FirstOrDefaultAsync(x => x.Pono == master.Pono);

            if (existingPo == null)
            {
                master.AddedBy = userName;
                master.AddedOn = DateTime.Now;
                master.IsApproved = false;
                master.IsVerified = false;
                master.IsSubmitted = master.IsSubmitted ?? false;

                if (master.IsSubmitted == true)
                {
                    master.SubmittedBy = userName;
                    master.SubmittedOn = DateTime.Now;
                }

                dbContext.Tbl60401purchaseOrderMasters.Add(master);
            }
            else
            {
                // If already approved, do NOT allow editing
                if (existingPo.IsApproved == true)
                {
                    throw new Exception("This purchase order has been approved and cannot be edited.");
                }

                // Update all fields (copy from master to existingPo)
                existingPo.Podate = master.Podate;
                existingPo.SupplierCode = master.SupplierCode;
                existingPo.SupplierQuoteNo = master.SupplierQuoteNo;
                existingPo.SupplierQuoteDate = master.SupplierQuoteDate;
                existingPo.SupplierRefNo = master.SupplierRefNo;
                existingPo.Attention = master.Attention;
                existingPo.SupplierContactNo = master.SupplierContactNo;
                existingPo.SupplierContactEmail = master.SupplierContactEmail;
                existingPo.SubjectTitle = master.SubjectTitle;
                existingPo.Project = master.Project;
                existingPo.ProjectMasterCode = master.ProjectMasterCode;
                existingPo.ProjectSubUnitCode = master.ProjectSubUnitCode;
                existingPo.PodueDate = master.PodueDate;

                existingPo.PreparedBy = master.PreparedBy;
                existingPo.PreparedOn = master.PreparedOn;
                existingPo.PorevisedBy = master.PorevisedBy;
                existingPo.PorevisedOn = master.PorevisedOn;
                existingPo.RevisionNo = master.RevisionNo;
                existingPo.IsObseleteVersion = master.IsObseleteVersion;
                existingPo.Posignatory = master.Posignatory;
                existingPo.PopaymentTerm = master.PopaymentTerm;
                existingPo.PodeliveryTerm = master.PodeliveryTerm;
                existingPo.PorevisionNo = master.PorevisionNo;
                existingPo.PodeliveryPeriod = master.PodeliveryPeriod;
                existingPo.PodocRequired = master.PodocRequired;
                existingPo.PowarrantyPeriod = master.PowarrantyPeriod;
                existingPo.PoshipTo = master.PoshipTo;
                existingPo.PobillTo = master.PobillTo;
                existingPo.Currency = master.Currency;
                existingPo.ExchangeRate = master.ExchangeRate;
                existingPo.PothanksNote = master.PothanksNote;
                existingPo.AdditionsText = master.AdditionsText;
                existingPo.DiscountsText = master.DiscountsText;
                existingPo.AdditionsAmount = master.AdditionsAmount;
                existingPo.DeductionsAmount = master.DeductionsAmount;
                existingPo.InventoryMasterGroupId = master.InventoryMasterGroupId;
                existingPo.PocategoryId = master.PocategoryId;
                existingPo.Rfqno = master.Rfqno;
                existingPo.TypeOfRequest = master.TypeOfRequest;
                existingPo.Pointroduction = master.Pointroduction;
                existingPo.Posummary = master.Posummary;
                existingPo.CompanyBranch = master.CompanyBranch;
                existingPo.SalesPersonCode = master.SalesPersonCode;
                existingPo.PoverifiedSign = master.PoverifiedSign;
                existingPo.PoapprovedSign = master.PoapprovedSign;
                existingPo.CurrencyId = master.CurrencyId ?? 1;
                existingPo.CurrencyRate = master.CurrencyRate ?? 1;
                existingPo.BaseCurrencyId = master.BaseCurrencyId ?? 1;
                existingPo.Posignatory = master.Posignatory;
                existingPo.PoverifiedSign = master.PoverifiedSign;
                existingPo.PoapprovedSign = master.PoapprovedSign;
                // Submit
                if (master.IsSubmitted == true && existingPo.IsSubmitted != true)
                {
                    existingPo.IsSubmitted = true;
                    existingPo.SubmittedBy = userName;
                    existingPo.SubmittedOn = DateTime.Now;
                }

                // Verify
                if (master.IsVerified == true && existingPo.IsVerified != true)
                {
                    if (existingPo.IsSubmitted != true)
                        throw new Exception("Cannot verify before submitting.");
                    existingPo.IsVerified = true;
                    existingPo.VerifiedBy = userName;
                    existingPo.VerifiedOn = DateTime.Now;
                }

                // Approve
                if (master.IsApproved == true && existingPo.IsApproved != true)
                {
                    if (existingPo.IsVerified != true)
                        throw new Exception("Cannot approve before verification.");
                    existingPo.IsApproved = true;
                    existingPo.ApprovedBy = userName;
                    existingPo.ApprovedOn = DateTime.Now;
                }

                existingPo.ModifiedBy = userName;
                existingPo.ModifiedOn = DateTime.Now;
            }

            // --- CHILDREN UPSERT/DELETE ---
            var existingChildren = await dbContext.Tbl60402purchaseOrderChildren
                .Where(x => x.Pono == pono)
                .ToListAsync();

            var incomingChildren = children;
            var incomingIds = incomingChildren.Where(c => c.PochildNo > 0).Select(c => c.PochildNo).ToList();

            // Update existing children
            foreach (var child in incomingChildren.Where(c => c.PochildNo > 0))
            {
                var entity = existingChildren.FirstOrDefault(x => x.PochildNo == child.PochildNo);
                if (entity != null)
                {
                    dbContext.Entry(entity).CurrentValues.SetValues(child);
                }
            }

            // Insert new children
            var newChildren = incomingChildren.Where(c => c.PochildNo == 0).ToList();
            foreach (var child in newChildren)
            {
                child.Pono = pono;
                child.ItemDiscount = child.ItemDiscount * master.CurrencyRate;
                child.UnitPrice = child.UnitPrice * master.CurrencyRate;
                await dbContext.Tbl60402purchaseOrderChildren.AddAsync(child);
            }

            // Delete removed children
            var toDelete = existingChildren.Where(x => !incomingIds.Contains(x.PochildNo)).ToList();
            if (toDelete.Any())
                dbContext.Tbl60402purchaseOrderChildren.RemoveRange(toDelete);

            await dbContext.SaveChangesAsync();
            await _userActionLogger.LogAsync(
              module: "IMS > Save Purchase Order",
              actionDetail: $"Saved Purchase Order  {model.Master.Pono}",
              documentNo: $"{model.Master.Pono}"
            );
            await transaction.CommitAsync();
        });

        return Ok(new { success = true, message = "Purchase order saved successfully.", pono = model.Master.Pono });
    }
    catch (Exception ex)
    {
        return StatusCode(500, new { success = false, message = $"Server error: {ex.Message}" });
    }
}
