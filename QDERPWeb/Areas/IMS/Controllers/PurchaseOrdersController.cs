public async Task<IActionResult> GetGroupedPurchaseOrders(DateTime? fromDate, DateTime? toDate)
{
    if (!_tenantDbContextHelper.TryGetTenantAndDbContext(out var tenant, out var dbContext))
        return Unauthorized();

    // Default to current month if not provided
    if (!fromDate.HasValue)
        fromDate = new DateTime(DateTime.Now.Year, DateTime.Now.Month, 1);
    if (!toDate.HasValue)
        toDate = new DateTime(DateTime.Now.Year, DateTime.Now.Month, DateTime.DaysInMonth(DateTime.Now.Year, DateTime.Now.Month));

    var rawList = await dbContext.Qry60404purchaseOrderViewMasters
        .AsNoTracking()
        .Where(x => x.Podate >= fromDate && x.Podate <= toDate)
        .ToListAsync();

    var groupedList = rawList
        .GroupBy(po => System.Text.RegularExpressions.Regex.Replace(po.Pono, "-R\\d+$", ""))
        .Select(g =>
        {
            var latest = g.OrderByDescending(x => x.PorevisionId).First();

            return new
            {
                Pono = g.Key,
                LatestRevisionId = latest.PorevisionId,
                LatestRevisionNo = $"Rev-{latest.PorevisionId:00}",
                LastPODate = latest.Podate,
                SupplierName = latest.SupplierName,
                Status = latest.IsApproved ? "Approved" : "Pending",
                IsSubmitted = latest.IsSubmitted,
                IsVerified = latest.IsVerified,
                PorevisionNo = latest.PorevisionNo,
                IsApproved = latest.IsApproved,
                NoOfItems = latest.NoOfItems,
                OrderStatus = latest.OrderStatus,
                BillStatus = latest.BillStatus,
                TotalBeforeTax = latest.TotalBeforeTax,
                TotalDiscount = latest.TotalDiscount,
                TotalAfterDiscount = latest.TotalAfterDiscount,
                TotalTaxAmount = latest.TotalTaxAmount,
                TotalWithTax = latest.TotalWithTax,
                AdditionsAmount = latest.AdditionsAmount,
                DeductionsAmount = latest.DeductionsAmount,
                GrandTotal = latest.GrandTotal
            };
        })
        .OrderByDescending(x => x.LastPODate)
        .ToList();

    return Ok(groupedList);
