        public IActionResult GetAutoGeneratedPurchaseorderNumber()
        {
            try
            {
                // Step 1: Get DB context
                if (_tenantDbContextHelper.TryGetTenantAndDbContext(out Tenant tenant, out ERPMasterWtDataContext dbContext))
                {
                    // Step 2: Get DefaultcompanyID from session
                    string defaultCompanyString = HttpContext.Session.GetString("DefaultcompanyID") ?? "";
                    byte defaultCompanyByte = 0;

                    if (!string.IsNullOrEmpty(defaultCompanyString))
                    {
                        byte.TryParse(defaultCompanyString, out defaultCompanyByte);
                    }

                    byte companyId = defaultCompanyByte;

                    // Step 3: Get company details by CompanyId
                    var company = dbContext.Tbl901CompanyDetails
                        .FirstOrDefault(c => c.CompanyId == companyId);

                    if (company == null)
                    {
                        return NotFound("Company not found in Tbl901CompanyDetails.");
                    }

                    // Step 4: Get PurchaseOrderAbbrv, year digit, reset flag, and number of digits
                    string purchaseOrderAbbrv = company.PurchaseOrderAbbrv ?? "";
                    int yearInDigit = company.InvoiceYearDigits ?? 0;
                    bool isResetByYear = company.IsResetInvoiceInYear ?? false;

                    int noOfDigits = dbContext.Tbl901CompanyDetails02s
                        .Where(c => c.CompanyId == company.CompanyId)
                        .Select(c => c.NoOfDigitsToInventoryQuotation ?? 5)
                        .FirstOrDefault();

                    DateTime currentDate = DateTime.Now;
                    string yearPart = currentDate.Year.ToString();

                    if (yearInDigit > 0)
                        yearPart = yearPart.Substring(yearPart.Length - yearInDigit, yearInDigit);
                    else
                        yearPart = "";

                    string basePrefix = $"{purchaseOrderAbbrv}{yearPart}-";

                    // Step 5: Get existing matching PO numbers
                    var poNos = dbContext.Tbl60401purchaseOrderMasters
                        .Where(x => x.Pono.StartsWith(basePrefix))
                        .Select(x => x.Pono)
                        .ToList();

                    // Step 6: Extract and compute next number
                    int maxNumber = poNos
                        .Select(no => int.TryParse(no?.Substring(no.Length - noOfDigits), out int num) ? num : 0)
                        .DefaultIfEmpty(0)
                        .Max();

                    int nextNumber = maxNumber + 1;
                    string nextPono = $"{basePrefix}{nextNumber.ToString().PadLeft(noOfDigits, '0')}";

                    return Ok(new { Pono = nextPono, success = true });
                }
                else
                {
                    _logger.LogWarning("Invalid tenant context when generating PurchaseOrderNo.");
                    return Unauthorized(new { message = "Invalid tenant." });
                }
            }
            catch (Exception ex)
            {
                _logger.LogError($"Error in GetAutoGeneratedPurchaseorderNumber: {ex.Message}");
                return StatusCode(500, new { message = "An error occurred while generating Purchase Order No.", error = ex.Message });
            }
        }



        private string GetAbbreviatedCompanyCode(string companyNameShort)
        {
            if (string.IsNullOrWhiteSpace(companyNameShort))
                return "UNK"; // Default fallback

            var trimmed = companyNameShort.Trim();

            if (trimmed.Length <= 5)
                return trimmed.ToUpper();

            var words = trimmed.Split(new[] { ' ', '-', '_' }, StringSplitOptions.RemoveEmptyEntries);
            var initials = string.Concat(words.Select(w => char.ToUpper(w[0])));

            return initials.Length >= 3 ? initials.Substring(0, 3) : initials.PadRight(3);
        }

