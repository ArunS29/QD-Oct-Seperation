        private string GetAbbreviatedCompanyCode(string EquipPOAbbrv, int yearInDigit, DateTime invoiceDate, bool isResetByYear, ERPMasterWtDataContext dbContext)
        {
            try
            {
                var mprNumbers = dbContext.Tbl40126PropertyPomasters
                     .Where(d => !string.IsNullOrEmpty(d.Pono) && d.Pono.Length >= 5 &&
                                 (!isResetByYear || (d.Podate.HasValue && d.Podate.Value.Year == invoiceDate.Year)))
                     .Select(d => d.Pono)
                     .ToList();



                int maxRunningNumber = mprNumbers
                    .Select(no => int.TryParse(no.Substring(no.Length - 5), out int num) ? num : 0)
                    .DefaultIfEmpty(0)
                    .Max();

                maxRunningNumber += 1;




                int maxRunningNumber = mprNumbers
                    .Select(no => int.TryParse(no.Substring(no.Length - 5), out int num) ? num : 0)
                    .DefaultIfEmpty(0)
                    .Max();

                maxRunningNumber += 1;


                string strNewNo = maxRunningNumber.ToString().PadLeft(5, '0');

                string strYear = yearInDigit > 0
                    ? invoiceDate.Year.ToString().Substring(4 - yearInDigit, yearInDigit)
                    : "";

                return $"{EquipPOAbbrv}{strYear}-{strNewNo}";
            }
            catch
            {
                string strYear = yearInDigit > 0
                    ? invoiceDate.Year.ToString().Substring(4 - yearInDigit, yearInDigit)
                    : "";

                return $"{EquipPOAbbrv}{strYear}-00001";
            }
        }





