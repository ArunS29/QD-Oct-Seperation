        [HttpDelete("{poNo}")]
        public async Task<IActionResult> DeletePurchaseOrder(string poNo)
        {
            if (string.IsNullOrWhiteSpace(poNo))
                return BadRequest(new { message = "PO number is required", success = false });

            if (!_tenantDbContextHelper.TryGetTenantAndDbContext(out Tenant tenant, out ERPMasterWtDataContext dbContext))
                return Unauthorized(new { message = "Invalid tenant", success = false });

            try
            {
                var existingPo = await dbContext.Tbl40126PropertyPomasters
                  .FirstOrDefaultAsync(x => x.Pono.Trim().ToLower() == poNo.Trim().ToLower());


                if (existingPo == null)
                    return NotFound(new { message = $"Purchase order {poNo} not found in tenant {tenant}.", success = false });

                if (existingPo == null)
                    return BadRequest(new { message = "Cannot delete: PO has already been submitted.", success = false });

                if (existingPo == null)
                    return BadRequest(new { message = "Cannot delete: PO has already been verified.", success = false });

                if (existingPo == null)
                    return BadRequest(new { message = "Cannot delete: PO has already been approved.", success = false });

                var children = await dbContext.Tbl40127PropertyPochildren
                    .Where(c => c.PropertyPono == poNo)
                    .ToListAsync();

                dbContext.Tbl40127PropertyPochildren.RemoveRange(children);

                dbContext.Tbl40126PropertyPomasters.Remove(existingPo);

                await dbContext.SaveChangesAsync();

                return Ok(new { message = $"Purchase order {poNo} deleted successfully", success = true });
            }
            catch (Exception ex)
            {
                // Optional: log the error
                return StatusCode(500, new { message = "Error deleting purchase order: " + ex.Message, success = false });
            }
        }


